//! Cooperative-matrix (WMMA) kernels. `emit_f16_gemm_test` is the smallest
//! useful kernel: it checks that the device, the features and the compile
//! path work, and measures the matrix-core throughput.

pub const COOPMAT_VERSION: &str = "coopmatgen-glsl-v1";

pub const PREAMBLE: &str = "#version 450
#extension GL_KHR_cooperative_matrix : enable
#extension GL_KHR_memory_scope_semantics : enable
#extension GL_EXT_shader_explicit_arithmetic_types_float16 : enable
#extension GL_EXT_shader_16bit_storage : enable
#extension GL_KHR_shader_subgroup_basic : enable
";

/// `C[M x N] (f32, row-major) = A[M x K] (f16, row-major) * B` where `B` is
/// stored column-major (`b[n * K + k]`). One subgroup per 16 x 16 tile of `C`,
/// workgroups numbered `tm * (N / 16) + tn`. Push constants: `m n k`.
/// Bindings: 0 A, 1 B, 2 C.
pub fn emit_f16_gemm_test() -> String {
    format!(
        "{PREAMBLE}// Generated by lev-forge ({COOPMAT_VERSION}): f16 gemm test
layout(local_size_x = 64) in;
layout(std430, set = 0, binding = 0) readonly buffer A {{ float16_t a[]; }};
layout(std430, set = 0, binding = 1) readonly buffer B {{ float16_t b[]; }};
layout(std430, set = 0, binding = 2) writeonly buffer C {{ float c[]; }};
layout(push_constant) uniform P {{ uint m; uint n; uint k; }} p;
void main() {{
    uint tiles_n = p.n / 16u;
    uint tm = gl_WorkGroupID.x / tiles_n;
    uint tn = gl_WorkGroupID.x % tiles_n;
    coopmat<float, gl_ScopeSubgroup, 16, 16, gl_MatrixUseAccumulator> acc = coopmat<float, gl_ScopeSubgroup, 16, 16, gl_MatrixUseAccumulator>(0.0);
    for (uint k0 = 0u; k0 < p.k; k0 += 16u) {{
        coopmat<float16_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseA> ma;
        coopmat<float16_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseB> mb;
        coopMatLoad(ma, a, tm * 16u * p.k + k0, p.k, gl_CooperativeMatrixLayoutRowMajor);
        coopMatLoad(mb, b, tn * 16u * p.k + k0, p.k, gl_CooperativeMatrixLayoutColumnMajor);
        acc = coopMatMulAdd(ma, mb, acc);
    }}
    coopMatStore(acc, c, tm * 16u * p.n + tn * 16u, p.n, gl_CooperativeMatrixLayoutRowMajor);
}}
"
    )
}

/// Tokens per matrix-core GEMM chunk (4 subgroups x 16 tokens).
pub const GEMM_TOKENS: usize = 64;

/// f32 activations to f16, element-wise. Bindings: 0 x (f32), 1 out (f16).
pub fn emit_act_f16() -> String {
    format!(
        "{PREAMBLE}// Generated by lev-forge ({COOPMAT_VERSION}): activations to f16
layout(local_size_x = 256) in;
layout(std430, set = 0, binding = 0) readonly buffer X {{ float x[]; }};
layout(std430, set = 0, binding = 1) writeonly buffer O {{ float16_t o[]; }};
void main() {{ uint i = gl_GlobalInvocationID.x; o[i] = float16_t(x[i]); }}
"
    )
}

/// Q4_K weights times `GEMM_TOKENS` f16 activation vectors on the matrix
/// cores. A workgroup of four subgroups (`wave` lanes each) owns 32 weight
/// rows and all tokens: for each 32-element K step the 32 x 32 weight tile is
/// dequantized to f16 in shared memory (work items of one row and four
/// elements, spread over the workgroup's threads), then every subgroup
/// multiplies it with its 16 tokens (two 16 x 16 x 16 products per row block).
/// The kernel must be created with subgroup size `wave`. Rows must be a
/// multiple of 32. Bindings: 0 weights (uint), 1 x (f16, `[token][cols]`),
/// 2 y (f32, `[token][rows]`). Push: rows, blocks per row.
pub fn emit_q4k_gemm(wave: usize) -> String {
    assert!(wave == 32 || wave == 64);
    let threads = 4 * wave;
    let items = 256 / threads;
    let mut o = format!(
        "{PREAMBLE}// Generated by lev-forge ({COOPMAT_VERSION}): q4k gemm, {GEMM_TOKENS} tokens, wave {wave}
layout(local_size_x = {threads}) in;
layout(std430, set = 0, binding = 0) readonly buffer W {{ uint w[]; }};
layout(std430, set = 0, binding = 1) readonly buffer X {{ float16_t x[]; }};
layout(std430, set = 0, binding = 2) writeonly buffer Y {{ float y[]; }};
layout(push_constant) uniform P {{ uint rows; uint bpr; }} p;
shared float16_t wsh[32 * 32];

uint sbyte(uint bi, uint k) {{ return (w[bi + 1u + (k >> 2u)] >> ((k & 3u) * 8u)) & 255u; }}
void scale_min(uint bi, uint j, out uint sc, out uint m) {{
    if (j < 4u) {{ sc = sbyte(bi, j) & 63u; m = sbyte(bi, j + 4u) & 63u; }}
    else {{
        sc = (sbyte(bi, j + 4u) & 15u) | ((sbyte(bi, j - 4u) >> 6u) << 4u);
        m = (sbyte(bi, j + 4u) >> 4u) | ((sbyte(bi, j) >> 6u) << 4u);
    }}
}}

void main() {{
    uint tid = gl_LocalInvocationID.x;
    uint sg = tid / {wave}u;
    uint row0 = gl_WorkGroupID.x * 32u;
    uint cols = p.bpr * 256u;
    coopmat<float, gl_ScopeSubgroup, 16, 16, gl_MatrixUseAccumulator> acc0 = coopmat<float, gl_ScopeSubgroup, 16, 16, gl_MatrixUseAccumulator>(0.0);
    coopmat<float, gl_ScopeSubgroup, 16, 16, gl_MatrixUseAccumulator> acc1 = coopmat<float, gl_ScopeSubgroup, 16, 16, gl_MatrixUseAccumulator>(0.0);
    for (uint step = 0u; step < p.bpr * 8u; step++) {{
        uint b = step >> 3u;
        uint j = step & 7u;
        uint byteoff = 16u + (j >> 1u) * 32u;
        uint sh = (j & 1u) * 4u;
"
    );
    for q in 0..items {
        o += &format!(
            "        {{
            uint item = tid + {}u;
            uint r = item >> 3u;
            uint g = item & 7u;
            uint bi = (min(row0 + r, p.rows - 1u) * p.bpr + b) * 36u;
            vec2 dm = unpackHalf2x16(w[bi]);
            uint sc; uint m;
            scale_min(bi, j, sc, m);
            float dsc = dm.x * float(sc);
            float dmn = dm.y * float(m);
            uint word = w[bi + ((byteoff + g * 4u) >> 2u)] >> sh;
            uint base = r * 32u + g * 4u;
            wsh[base + 0u] = float16_t(dsc * float(word & 15u) - dmn);
            wsh[base + 1u] = float16_t(dsc * float((word >> 8u) & 15u) - dmn);
            wsh[base + 2u] = float16_t(dsc * float((word >> 16u) & 15u) - dmn);
            wsh[base + 3u] = float16_t(dsc * float((word >> 24u) & 15u) - dmn);
        }}
",
            q * threads
        );
    }
    o += "        barrier();
        for (uint kk = 0u; kk < 32u; kk += 16u) {
            coopmat<float16_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseA> a0;
            coopmat<float16_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseA> a1;
            coopmat<float16_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseB> bm;
            coopMatLoad(a0, wsh, kk, 32u, gl_CooperativeMatrixLayoutRowMajor);
            coopMatLoad(a1, wsh, 16u * 32u + kk, 32u, gl_CooperativeMatrixLayoutRowMajor);
            coopMatLoad(bm, x, sg * 16u * cols + step * 32u + kk, cols, gl_CooperativeMatrixLayoutColumnMajor);
            acc0 = coopMatMulAdd(a0, bm, acc0);
            acc1 = coopMatMulAdd(a1, bm, acc1);
        }
        barrier();
    }
    coopMatStore(acc0, y, sg * 16u * p.rows + row0, p.rows, gl_CooperativeMatrixLayoutColumnMajor);
    coopMatStore(acc1, y, sg * 16u * p.rows + row0 + 16u, p.rows, gl_CooperativeMatrixLayoutColumnMajor);
}
";
    o
}

/// Q6_K counterpart of `emit_q4k_gemm`. A 32-element K step is one (half,
/// plane) pair of a 256-element block: 32 consecutive `ql` bytes, 32
/// consecutive `qh` bytes and two int8 scales. Block starts are only 2-byte
/// aligned, so words are assembled from two aligned loads.
pub fn emit_q6k_gemm(wave: usize) -> String {
    assert!(wave == 32 || wave == 64);
    let threads = 4 * wave;
    let items = 256 / threads;
    let mut o = format!(
        "{PREAMBLE}// Generated by lev-forge ({COOPMAT_VERSION}): q6k gemm, {GEMM_TOKENS} tokens, wave {wave}
layout(local_size_x = {threads}) in;
layout(std430, set = 0, binding = 0) readonly buffer W {{ uint w[]; }};
layout(std430, set = 0, binding = 1) readonly buffer X {{ float16_t x[]; }};
layout(std430, set = 0, binding = 2) writeonly buffer Y {{ float y[]; }};
layout(push_constant) uniform P {{ uint rows; uint bpr; }} p;
shared float16_t wsh[32 * 32];

uint word(uint bo) {{
    uint i = bo >> 2u;
    uint s = (bo & 3u) * 8u;
    uint lo = w[i];
    if (s == 0u) {{ return lo; }}
    return (lo >> s) | (w[i + 1u] << (32u - s));
}}
uint byt(uint bo) {{ return (w[bo >> 2u] >> ((bo & 3u) * 8u)) & 255u; }}

void main() {{
    uint tid = gl_LocalInvocationID.x;
    uint sg = tid / {wave}u;
    uint row0 = gl_WorkGroupID.x * 32u;
    uint cols = p.bpr * 256u;
    coopmat<float, gl_ScopeSubgroup, 16, 16, gl_MatrixUseAccumulator> acc0 = coopmat<float, gl_ScopeSubgroup, 16, 16, gl_MatrixUseAccumulator>(0.0);
    coopmat<float, gl_ScopeSubgroup, 16, 16, gl_MatrixUseAccumulator> acc1 = coopmat<float, gl_ScopeSubgroup, 16, 16, gl_MatrixUseAccumulator>(0.0);
    for (uint step = 0u; step < p.bpr * 8u; step++) {{
        uint b = step >> 3u;
        uint nn = (step >> 2u) & 1u;
        uint pl = step & 3u;
"
    );
    for q in 0..items {
        o += &format!(
            "        {{
            uint item = tid + {}u;
            uint r = item >> 3u;
            uint g = item & 7u;
            uint base = (min(row0 + r, p.rows - 1u) * p.bpr + b) * 210u;
            uint qw = word(base + 64u * nn + 32u * (pl & 1u) + g * 4u) >> ((pl >> 1u) * 4u);
            uint hw = word(base + 128u + 32u * nn + g * 4u) >> (pl * 2u);
            float sc = float(int(byt(base + 192u + 8u * nn + 2u * pl + (g >> 2u)) << 24u) >> 24);
            float d = unpackHalf2x16(byt(base + 208u) | (byt(base + 209u) << 8u)).x;
            float ds = d * sc;
            for (uint e = 0u; e < 4u; e++) {{
                uint q = ((qw >> (8u * e)) & 15u) | (((hw >> (8u * e)) & 3u) << 4u);
                wsh[r * 32u + g * 4u + e] = float16_t(ds * float(int(q) - 32));
            }}
        }}
",
            q * threads
        );
    }
    o += "        barrier();
        for (uint kk = 0u; kk < 32u; kk += 16u) {
            coopmat<float16_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseA> a0;
            coopmat<float16_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseA> a1;
            coopmat<float16_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseB> bm;
            coopMatLoad(a0, wsh, kk, 32u, gl_CooperativeMatrixLayoutRowMajor);
            coopMatLoad(a1, wsh, 16u * 32u + kk, 32u, gl_CooperativeMatrixLayoutRowMajor);
            coopMatLoad(bm, x, sg * 16u * cols + step * 32u + kk, cols, gl_CooperativeMatrixLayoutColumnMajor);
            acc0 = coopMatMulAdd(a0, bm, acc0);
            acc1 = coopMatMulAdd(a1, bm, acc1);
        }
        barrier();
    }
    coopMatStore(acc0, y, sg * 16u * p.rows + row0, p.rows, gl_CooperativeMatrixLayoutColumnMajor);
    coopMatStore(acc1, y, sg * 16u * p.rows + row0 + 16u, p.rows, gl_CooperativeMatrixLayoutColumnMajor);
}
";
    o
}
/// Q4_K GEMM that dequantizes a whole 256-element block of 32 rows into a
/// 32 x 256 shared tile per iteration (one thread per row and 64-element
/// chunk, so every scale pair is decoded once per block instead of once per
/// 32-element step and each thread issues wide stores), then runs 16 K steps
/// of matrix products from it, with two barriers per block. Wave 32 only
/// (workgroup of 128). Each subgroup multiplies `tokens / 4` tokens (16-wide
/// tiles), so `tokens = 128` doubles the matrix work per dequantized weight.
/// Same bindings and push constants as `emit_q4k_gemm`; `y` is
/// `[token][rows]` for `tokens` tokens.
pub fn emit_q4k_gemm_blocked_tokens(tokens: usize) -> String {
    assert!(tokens == 64 || tokens == 128);
    let tt = tokens / 64; // 16-token tiles per subgroup
    let mut o = format!(
        "{PREAMBLE}// Generated by lev-forge ({COOPMAT_VERSION}): q4k gemm blocked, {tokens} tokens, wave 32
layout(local_size_x = 128) in;
layout(std430, set = 0, binding = 0) readonly buffer W {{ uint w[]; }};
layout(std430, set = 0, binding = 1) readonly buffer X {{ float16_t x[]; }};
layout(std430, set = 0, binding = 2) writeonly buffer Y {{ float y[]; }};
layout(push_constant) uniform P {{ uint rows; uint bpr; }} p;
// 32 rows x 256 k as f16vec4, row stride 66 vec4 (264 halves) to spread LDS banks.
shared f16vec4 wsh[32 * 66];

uint sbyte(uint bi, uint k) {{ return (w[bi + 1u + (k >> 2u)] >> ((k & 3u) * 8u)) & 255u; }}
void scale_min(uint bi, uint j, out uint sc, out uint m) {{
    if (j < 4u) {{ sc = sbyte(bi, j) & 63u; m = sbyte(bi, j + 4u) & 63u; }}
    else {{
        sc = (sbyte(bi, j + 4u) & 15u) | ((sbyte(bi, j - 4u) >> 6u) << 4u);
        m = (sbyte(bi, j + 4u) >> 4u) | ((sbyte(bi, j) >> 6u) << 4u);
    }}
}}

void main() {{
    uint tid = gl_LocalInvocationID.x;
    uint sg = tid >> 5u;
    uint row0 = gl_WorkGroupID.x * 32u;
    uint cols = p.bpr * 256u;
    uint r = tid >> 2u;
    uint c = tid & 3u;
    uint wrow = min(row0 + r, p.rows - 1u);
"
    );
    for t in 0..tt {
        for rb in 0..2 {
            o += &format!("    coopmat<float, gl_ScopeSubgroup, 16, 16, gl_MatrixUseAccumulator> acc{rb}_{t} = coopmat<float, gl_ScopeSubgroup, 16, 16, gl_MatrixUseAccumulator>(0.0);\n");
        }
    }
    o += "    for (uint b = 0u; b < p.bpr; b++) {
        uint bi = (wrow * p.bpr + b) * 36u;
        vec2 dm = unpackHalf2x16(w[bi]);
        uint sc1; uint m1; uint sc2; uint m2;
        scale_min(bi, c * 2u, sc1, m1);
        scale_min(bi, c * 2u + 1u, sc2, m2);
        float d1 = dm.x * float(sc1);
        float n1 = dm.y * float(m1);
        float d2 = dm.x * float(sc2);
        float n2 = dm.y * float(m2);
        uint qb = bi + 4u + c * 8u;
        uint base4 = r * 66u + c * 16u;
        for (uint i = 0u; i < 8u; i++) {
            uint word = w[qb + i];
            wsh[base4 + i] = f16vec4(float16_t(d1 * float(word & 15u) - n1),
                                     float16_t(d1 * float((word >> 8u) & 15u) - n1),
                                     float16_t(d1 * float((word >> 16u) & 15u) - n1),
                                     float16_t(d1 * float((word >> 24u) & 15u) - n1));
            wsh[base4 + 8u + i] = f16vec4(float16_t(d2 * float((word >> 4u) & 15u) - n2),
                                          float16_t(d2 * float((word >> 12u) & 15u) - n2),
                                          float16_t(d2 * float((word >> 20u) & 15u) - n2),
                                          float16_t(d2 * float((word >> 28u) & 15u) - n2));
        }
        barrier();
        for (uint kk = 0u; kk < 256u; kk += 16u) {
            coopmat<float16_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseA> a0;
            coopmat<float16_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseA> a1;
            coopMatLoad(a0, wsh, kk / 4u, 66u, gl_CooperativeMatrixLayoutRowMajor);
            coopMatLoad(a1, wsh, 16u * 66u + kk / 4u, 66u, gl_CooperativeMatrixLayoutRowMajor);
";
    for t in 0..tt {
        o += &format!(
            "            {{
                coopmat<float16_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseB> bm;
                coopMatLoad(bm, x, (sg * {tt}u + {t}u) * 16u * cols + b * 256u + kk, cols, gl_CooperativeMatrixLayoutColumnMajor);
                acc0_{t} = coopMatMulAdd(a0, bm, acc0_{t});
                acc1_{t} = coopMatMulAdd(a1, bm, acc1_{t});
            }}
"
        );
    }
    o += "        }
        barrier();
    }
";
    for t in 0..tt {
        o += &format!("    coopMatStore(acc0_{t}, y, (sg * {tt}u + {t}u) * 16u * p.rows + row0, p.rows, gl_CooperativeMatrixLayoutColumnMajor);\n    coopMatStore(acc1_{t}, y, (sg * {tt}u + {t}u) * 16u * p.rows + row0 + 16u, p.rows, gl_CooperativeMatrixLayoutColumnMajor);\n");
    }
    o += "}\n";
    o
}

/// 64-token form of `emit_q4k_gemm_blocked_tokens`.
pub fn emit_q4k_gemm_blocked() -> String {
    emit_q4k_gemm_blocked_tokens(64)
}
/// Q6_K counterpart of `emit_q4k_gemm_blocked`: one thread per row and
/// (128-element half, 16-position) piece of a block dequantizes the four
/// planes of its 16 positions (64 elements) with one scale decode, loading its
/// `ql`/`qh` runs as unaligned 16-byte reads (blocks are only 2-byte aligned).
pub fn emit_q6k_gemm_blocked_tokens(tokens: usize) -> String {
    assert!(tokens == 64 || tokens == 128);
    let tt = tokens / 64;
    let mut o = format!(
        "{PREAMBLE}#extension GL_EXT_control_flow_attributes : enable
// Generated by lev-forge ({COOPMAT_VERSION}): q6k gemm blocked, {tokens} tokens, wave 32
layout(local_size_x = 128) in;
layout(std430, set = 0, binding = 0) readonly buffer W {{ uint w[]; }};
layout(std430, set = 0, binding = 1) readonly buffer X {{ float16_t x[]; }};
layout(std430, set = 0, binding = 2) writeonly buffer Y {{ float y[]; }};
layout(push_constant) uniform P {{ uint rows; uint bpr; }} p;
shared f16vec4 wsh[32 * 66];

// 16 bytes at byte offset `bo` (any 2-byte alignment) as four words.
uvec4 ld16(uint bo) {{
    uint i = bo >> 2u;
    uint s = (bo & 3u) * 8u;
    uint a = w[i]; uint b = w[i + 1u]; uint c = w[i + 2u]; uint d = w[i + 3u]; uint e = w[i + 4u];
    return uvec4((a >> s) | ((b << (31u - s)) << 1u), (b >> s) | ((c << (31u - s)) << 1u),
                 (c >> s) | ((d << (31u - s)) << 1u), (d >> s) | ((e << (31u - s)) << 1u));
}}
uint byt(uint bo) {{ return (w[bo >> 2u] >> ((bo & 3u) * 8u)) & 255u; }}

void main() {{
    uint tid = gl_LocalInvocationID.x;
    uint sg = tid >> 5u;
    uint row0 = gl_WorkGroupID.x * 32u;
    uint cols = p.bpr * 256u;
    uint r = tid >> 2u;
    uint c = tid & 3u;
    uint nn = c >> 1u;
    uint lh = c & 1u;
    uint wrow = min(row0 + r, p.rows - 1u);
    for (uint b = 0u; b < p.bpr; b++) {{
        uint base = (wrow * p.bpr + b) * 210u;
        uvec4 qlA = ld16(base + 64u * nn + 16u * lh);
        uvec4 qlB = ld16(base + 64u * nn + 32u + 16u * lh);
        uvec4 qhv = ld16(base + 128u + 32u * nn + 16u * lh);
        float d = unpackHalf2x16(byt(base + 208u) | (byt(base + 209u) << 8u)).x;
        float ds[4];
        [[unroll]] for (uint pl = 0u; pl < 4u; pl++) {{
            ds[pl] = d * float(int(byt(base + 192u + 8u * nn + 2u * pl + lh) << 24u) >> 24);
        }}
        [[unroll]] for (uint t = 0u; t < 4u; t++) {{
            uint a = qlA[t]; uint bq = qlB[t]; uint h = qhv[t];
            [[unroll]] for (uint pl = 0u; pl < 4u; pl++) {{
                uint nib = pl == 0u ? (a & 0x0F0F0F0Fu) : (pl == 1u ? (bq & 0x0F0F0F0Fu) : (pl == 2u ? ((a >> 4u) & 0x0F0F0F0Fu) : ((bq >> 4u) & 0x0F0F0F0Fu)));
                uint qv = nib | (((h >> (2u * pl)) & 0x03030303u) << 4u);
                wsh[r * 66u + nn * 32u + pl * 8u + lh * 4u + t] = f16vec4(
                    float16_t(ds[pl] * float(int(qv & 255u) - 32)),
                    float16_t(ds[pl] * float(int((qv >> 8u) & 255u) - 32)),
                    float16_t(ds[pl] * float(int((qv >> 16u) & 255u) - 32)),
                    float16_t(ds[pl] * float(int((qv >> 24u) & 255u) - 32)));
            }}
        }}
"
    );
    // Accumulators are declared before the block loop: insert them after `wrow`.
    let mut acc = String::new();
    for t in 0..tt {
        for rb in 0..2 {
            acc += &format!("    coopmat<float, gl_ScopeSubgroup, 16, 16, gl_MatrixUseAccumulator> acc{rb}_{t} = coopmat<float, gl_ScopeSubgroup, 16, 16, gl_MatrixUseAccumulator>(0.0);\n");
        }
    }
    o = o.replacen("    for (uint b = 0u; b < p.bpr; b++) {\n", &format!("{acc}    for (uint b = 0u; b < p.bpr; b++) {{\n"), 1);
    o += "        barrier();
        for (uint kk = 0u; kk < 256u; kk += 16u) {
            coopmat<float16_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseA> a0;
            coopmat<float16_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseA> a1;
            coopMatLoad(a0, wsh, kk / 4u, 66u, gl_CooperativeMatrixLayoutRowMajor);
            coopMatLoad(a1, wsh, 16u * 66u + kk / 4u, 66u, gl_CooperativeMatrixLayoutRowMajor);
";
    for t in 0..tt {
        o += &format!(
            "            {{
                coopmat<float16_t, gl_ScopeSubgroup, 16, 16, gl_MatrixUseB> bm;
                coopMatLoad(bm, x, (sg * {tt}u + {t}u) * 16u * cols + b * 256u + kk, cols, gl_CooperativeMatrixLayoutColumnMajor);
                acc0_{t} = coopMatMulAdd(a0, bm, acc0_{t});
                acc1_{t} = coopMatMulAdd(a1, bm, acc1_{t});
            }}
"
        );
    }
    o += "        }
        barrier();
    }
";
    for t in 0..tt {
        o += &format!("    coopMatStore(acc0_{t}, y, (sg * {tt}u + {t}u) * 16u * p.rows + row0, p.rows, gl_CooperativeMatrixLayoutColumnMajor);\n    coopMatStore(acc1_{t}, y, (sg * {tt}u + {t}u) * 16u * p.rows + row0 + 16u, p.rows, gl_CooperativeMatrixLayoutColumnMajor);\n");
    }
    o += "}\n";
    o
}

