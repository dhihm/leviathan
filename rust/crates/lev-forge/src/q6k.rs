//! Q6_K matvec: schedule derivation and GLSL emitter.
//!
//! Same split-block idea as the Q4_K kernel: a 210-byte block is 16 units of
//! 4 bytes per quant plane, adjacent threads take adjacent units. A Q6_K block
//! is only 2-byte aligned (210 is not a multiple of 4), so words are loaded
//! with an unaligned two-word helper.

use crate::schedule::DeviceCaps;

pub const KERNEL_NAME: &str = "q6k.matvec";
pub const CODEGEN_VERSION: &str = "q6kgen-glsl-v2";
pub const BLOCK_BYTES: usize = 210;
const UNITS_PER_BLOCK: usize = 16;

/// `t`: threads per row, `r`: rows per workgroup, `nb`: input columns per weight read (1 or 2).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct Q6kSchedule {
    pub t: u32,
    pub r: u32,
    pub nb: u32,
}

impl Q6kSchedule {
    pub const BASELINE: Q6kSchedule = Q6kSchedule { t: 8, r: 1, nb: 1 };

    pub fn invocations(&self) -> u32 {
        self.t * self.r
    }
}

const T_CHOICES: [u32; 5] = [8, 16, 32, 64, 128];
const R_CHOICES: [u32; 4] = [1, 2, 4, 8];

pub fn is_legal(s: &Q6kSchedule, blocks_per_row: usize, caps: &DeviceCaps) -> bool {
    matches!(s.nb, 1 | 2)
        && T_CHOICES.contains(&s.t)
        && R_CHOICES.contains(&s.r)
        && s.invocations() <= caps.max_workgroup_invocations
        && blocks_per_row * UNITS_PER_BLOCK >= s.t as usize
}

/// Baseline first, then every legal schedule with 32-256 invocations.
pub fn derive(blocks_per_row: usize, caps: &DeviceCaps) -> Vec<Q6kSchedule> {
    let mut out = vec![Q6kSchedule::BASELINE];
    for &t in &T_CHOICES {
        for &r in &R_CHOICES {
            if (32..=256).contains(&(t * r)) {
                out.push(Q6kSchedule { t, r, nb: 1 });
            }
        }
    }
    let mut seen = std::collections::HashSet::new();
    out.retain(|s| is_legal(s, blocks_per_row, caps) && seen.insert(*s));
    out
}

pub fn group_count(s: &Q6kSchedule, rows: u32) -> u32 {
    rows.div_ceil(s.r)
}

const HEADER: &str = r#"#version 450
// Generated by lev-forge (@VERSION@): @KERNEL@  T=@T@ R=@R@ NB=@NB@
layout(local_size_x = @T@, local_size_y = @R@, local_size_z = 1) in;
layout(std430, set = 0, binding = 0) readonly buffer Weights { uint w[]; };
layout(std430, set = 0, binding = 1) readonly buffer Input { vec4 x4[]; };
layout(std430, set = 0, binding = 2) writeonly buffer Output { float y[]; };
layout(push_constant) uniform Params { uint rows; uint blocks_per_row; } p;

// Q6_K block = 210 bytes: ql[128] | qh[64] | scales[16] (int8) | d (f16).
uint word(uint bo) {
    uint i = bo >> 2u;
    uint s = (bo & 3u) * 8u;
    uint lo = w[i];
    if (s == 0u) { return lo; }
    return (lo >> s) | (w[i + 1u] << (32u - s));
}

uint byt(uint bo) {
    return (w[bo >> 2u] >> ((bo & 3u) * 8u)) & 255u;
}

float sbyte(uint bo) {
    return float(int(byt(bo) << 24u) >> 24);
}

vec4 quants(uint lo, uint hi, uint shl, uint shh) {
    return vec4(
        float(int(((lo >> (shl)) & 15u) | (((hi >> (shh)) & 3u) << 4u)) - 32),
        float(int(((lo >> (shl + 8u)) & 15u) | (((hi >> (shh + 8u)) & 3u) << 4u)) - 32),
        float(int(((lo >> (shl + 16u)) & 15u) | (((hi >> (shh + 16u)) & 3u) << 4u)) - 32),
        float(int(((lo >> (shl + 24u)) & 15u) | (((hi >> (shh + 24u)) & 3u) << 4u)) - 32));
}

shared float partial[@RTN@];

void main() {
    uint t = gl_LocalInvocationID.x;
    uint ly = gl_LocalInvocationID.y;
    uint row = gl_WorkGroupID.x * @R@u + ly;
    uint xcol = p.blocks_per_row * 64u;
"#;

fn body(nb: u32) -> String {
    let mut o = String::new();
    for c in 0..nb {
        o += &format!("    float sum{c} = 0.0;\n");
    }
    o += "    if (row < p.rows) {
        uint units = p.blocks_per_row * 16u;
        uint rowbyte = row * p.blocks_per_row * 210u;
        for (uint n = t; n < units; n += @T@u) {
            uint b = n >> 4u;
            uint nn = (n >> 3u) & 1u;
            uint g = n & 7u;
            uint base = rowbyte + b * 210u;
            uint qa = word(base + 64u * nn + 4u * g);
            uint qb = word(base + 64u * nn + 4u * g + 32u);
            uint qh = word(base + 128u + 32u * nn + 4u * g);
            uint sb = base + 192u + 8u * nn + (g >> 2u);
            float s1 = sbyte(sb);
            float s2 = sbyte(sb + 2u);
            float s3 = sbyte(sb + 4u);
            float s4 = sbyte(sb + 6u);
            float d = unpackHalf2x16(byt(base + 208u) | (byt(base + 209u) << 8u)).x;
            uint xi = (b * 256u + 128u * nn + 4u * g) >> 2u;
            vec4 q1 = quants(qa, qh, 0u, 0u);
            vec4 q2 = quants(qb, qh, 0u, 2u);
            vec4 q3 = quants(qa, qh, 4u, 4u);
            vec4 q4 = quants(qb, qh, 4u, 6u);
";
    for c in 0..nb {
        o += &format!(
            "            sum{c} += d * (s1 * dot(q1, x4[xi + {c}u * xcol])
                          + s2 * dot(q2, x4[xi + 8u + {c}u * xcol])
                          + s3 * dot(q3, x4[xi + 16u + {c}u * xcol])
                          + s4 * dot(q4, x4[xi + 24u + {c}u * xcol]));
"
        );
    }
    o += "        }\n    }\n";
    for c in 0..nb {
        o += &format!("    partial[(ly * {nb}u + {c}u) * @T@u + t] = sum{c};\n");
    }
    o += "    memoryBarrierShared();
    barrier();
    for (uint s = @T@u / 2u; s > 0u; s >>= 1u) {
        if (t < s) {
";
    for c in 0..nb {
        o += &format!("            partial[(ly * {nb}u + {c}u) * @T@u + t] += partial[(ly * {nb}u + {c}u) * @T@u + t + s];\n");
    }
    o += "        }
        memoryBarrierShared();
        barrier();
    }
    if (t == 0u && row < p.rows) {
";
    for c in 0..nb {
        o += &format!("        y[{c}u * p.rows + row] = partial[(ly * {nb}u + {c}u) * @T@u];\n");
    }
    o += "    }\n}\n";
    o
}
#[derive(Debug, PartialEq, Eq)]
pub struct EmitError(pub String);

impl std::fmt::Display for EmitError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "invalid schedule: {}", self.0)
    }
}

impl std::error::Error for EmitError {}

pub fn emit_q6k_matvec(s: &Q6kSchedule) -> Result<String, EmitError> {
    if !T_CHOICES.contains(&s.t) || !R_CHOICES.contains(&s.r) || !matches!(s.nb, 1 | 2) || s.invocations() > 1024 {
        return Err(EmitError(format!("{s:?}")));
    }
    Ok([HEADER, &body(s.nb)]
        .concat()
        .replace("@VERSION@", CODEGEN_VERSION)
        .replace("@KERNEL@", KERNEL_NAME)
        .replace("@RTN@", &(s.t * s.r * s.nb).to_string())
        .replace("@NB@", &s.nb.to_string())
        .replace("@T@", &s.t.to_string())
        .replace("@R@", &s.r.to_string()))
}

#[cfg(test)]
mod tests {
    use super::*;

    const CAPS: DeviceCaps = DeviceCaps { subgroup_size: 64, max_workgroup_invocations: 1024 };

    #[test]
    fn baseline_first_unique_and_legal() {
        let c = derive(16, &CAPS);
        assert_eq!(c[0], Q6kSchedule::BASELINE);
        let mut seen = std::collections::HashSet::new();
        assert!(c.iter().all(|s| seen.insert(*s) && is_legal(s, 16, &CAPS)));
        assert!(c.len() > 4);
    }

    #[test]
    fn emission_is_deterministic_and_complete() {
        let a = emit_q6k_matvec(&Q6kSchedule { t: 32, r: 2, nb: 1 }).unwrap();
        assert_eq!(a, emit_q6k_matvec(&Q6kSchedule { t: 32, r: 2, nb: 1 }).unwrap());
        assert!(a.contains("local_size_x = 32, local_size_y = 2") && a.contains("shared float partial[64];"));
        assert!(!a.contains('@'));
        assert!(emit_q6k_matvec(&Q6kSchedule { t: 3, r: 1, nb: 1 }).is_err());
    }

    #[test]
    fn group_count_rounds_up() {
        assert_eq!(group_count(&Q6kSchedule { t: 8, r: 4, nb: 1 }, 10), 3);
    }
}
