//! GLSL (Vulkan compute) emitter for the Q4_K matvec.
//!
//! The kernel text is derived from the schedule parameters, not looked up:
//! thread mapping, the cooperative reduction and the workgroup shape are
//! emitted from `(t, r)`. Arithmetic follows the CPU reference exactly where
//! the order is observable: per element `(d*sc*q - dmin*m) * x`, ascending
//! blocks and elements; the cooperative form sums per-thread partials in
//! ascending thread order, a deterministic order that is not bit-identical to
//! the serial one.

use crate::schedule::Q4kSchedule;
use crate::sha256::sha256_hex;

pub const KERNEL_NAME: &str = "q4k.matvec";
pub const CODEGEN_VERSION: &str = "q4kgen-glsl-v9";
const MAX_INVOCATIONS: u32 = 1024;

#[derive(Debug, PartialEq, Eq)]
pub enum EmitError {
    InvalidSchedule(String),
}

impl std::fmt::Display for EmitError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::InvalidSchedule(m) => write!(f, "invalid schedule: {m}"),
        }
    }
}

impl std::error::Error for EmitError {}

const COMMON: &str = r#"#version 450
// Generated by lev-forge (@VERSION@): @KERNEL@  T=@T@ R=@R@
layout(local_size_x = @LX@, local_size_y = @LY@, local_size_z = 1) in;
layout(std430, set = 0, binding = 0) readonly buffer Weights { uint w[]; };
@XDECL@
layout(std430, set = 0, binding = 2) writeonly buffer Output { float y[]; };
layout(push_constant) uniform Params { uint rows; uint blocks_per_row; } p;

// Q4_K block = 144 bytes = 36 uints: [d,dmin as two halves][12 scale bytes][128 nibble bytes].
uint sbyte(uint bi, uint k) {
    return (w[bi + 1u + (k >> 2u)] >> ((k & 3u) * 8u)) & 255u;
}

void scale_min(uint bi, uint j, out uint sc, out uint m) {
    if (j < 4u) {
        sc = sbyte(bi, j) & 63u;
        m = sbyte(bi, j + 4u) & 63u;
    } else {
        sc = (sbyte(bi, j + 4u) & 15u) | ((sbyte(bi, j - 4u) >> 6u) << 4u);
        m = (sbyte(bi, j + 4u) >> 4u) | ((sbyte(bi, j) >> 6u) << 4u);
    }
}

float block_acc(float sum, uint blk, uint xoff) {
    uint bi = blk * 36u;
    vec2 dm = unpackHalf2x16(w[bi]);
    for (uint chunk = 0u; chunk < 4u; chunk++) {
        uint sc1; uint m1; uint sc2; uint m2;
        scale_min(bi, chunk * 2u, sc1, m1);
        scale_min(bi, chunk * 2u + 1u, sc2, m2);
        float d1 = dm.x * float(sc1);
        float mm1 = dm.y * float(m1);
        float d2 = dm.x * float(sc2);
        float mm2 = dm.y * float(m2);
        uint qb = bi + 4u + chunk * 8u;
        uint xb = xoff + chunk * 64u;
@LOOPS@
    }
    return sum;
}
"#;

const LOOPS_SCALAR: &str = r#"        for (uint l4 = 0u; l4 < 8u; l4++) {
            uint u = w[qb + l4];
            for (uint k = 0u; k < 4u; k++) {
                float q = float((u >> (k * 8u)) & 15u);
                sum += (d1 * q - mm1) * x[xb + l4 * 4u + k];
            }
        }
        for (uint l4 = 0u; l4 < 8u; l4++) {
            uint u = w[qb + l4];
            for (uint k = 0u; k < 4u; k++) {
                float q = float(((u >> (k * 8u)) >> 4u) & 15u);
                sum += (d2 * q - mm2) * x[xb + 32u + l4 * 4u + k];
            }
        }"#;

// Same per-element arithmetic and order as the scalar form; only the x loads
// are 16-byte (xb is a multiple of 64 floats, so every vec4 is aligned).
const LOOPS_VEC4: &str = r#"        for (uint l4 = 0u; l4 < 8u; l4++) {
            uint u = w[qb + l4];
            vec4 xv = x4[(xb >> 2u) + l4];
            sum += (d1 * float(u & 15u) - mm1) * xv.x;
            sum += (d1 * float((u >> 8u) & 15u) - mm1) * xv.y;
            sum += (d1 * float((u >> 16u) & 15u) - mm1) * xv.z;
            sum += (d1 * float((u >> 24u) & 15u) - mm1) * xv.w;
        }
        for (uint l4 = 0u; l4 < 8u; l4++) {
            uint u = w[qb + l4];
            vec4 xv = x4[(xb >> 2u) + 8u + l4];
            sum += (d2 * float((u >> 4u) & 15u) - mm2) * xv.x;
            sum += (d2 * float((u >> 12u) & 15u) - mm2) * xv.y;
            sum += (d2 * float((u >> 20u) & 15u) - mm2) * xv.z;
            sum += (d2 * float((u >> 28u) & 15u) - mm2) * xv.w;
        }"#;

const XDECL_SCALAR: &str = "layout(std430, set = 0, binding = 1) readonly buffer Input { float x[]; };";
const XDECL_VEC4: &str = "layout(std430, set = 0, binding = 1) readonly buffer Input { vec4 x4[]; };";

const MAIN_SERIAL: &str = r#"
void main() {
    uint row = gl_WorkGroupID.x * @R@u + gl_LocalInvocationID.x;
    if (row >= p.rows) { return; }
    float sum = 0.0;
    for (uint b = 0u; b < p.blocks_per_row; b++) {
        sum = block_acc(sum, row * p.blocks_per_row + b, b * 256u);
    }
    y[row] = sum;
}
"#;

const MAIN_COOPERATIVE: &str = r#"
shared float partial[@RT@];

void main() {
    uint t = gl_LocalInvocationID.x;
    uint ly = gl_LocalInvocationID.y;
    uint row = gl_WorkGroupID.x * @R@u + ly;
    float sum = 0.0;
    if (row < p.rows) {
        for (uint b = t; b < p.blocks_per_row; b += @T@u) {
            sum = block_acc(sum, row * p.blocks_per_row + b, b * 256u);
        }
    }
    partial[ly * @T@u + t] = sum;
    memoryBarrierShared();
    barrier();
    if (t == 0u && row < p.rows) {
        float s = 0.0;
        for (uint i = 0u; i < @T@u; i++) {
            s += partial[ly * @T@u + i];
        }
        y[row] = s;
    }
}
"#;

// Split-block mapping: a block is 16 units of 8 contiguous bytes (uints qb, qb+1)
// covering 8 low-nibble and 8 high-nibble elements; adjacent threads take
// adjacent units, so a wave reads contiguous weight bytes. The per-element form
// (d*sc*q - dmin*m)*x is factored to d*sc*sum(q*x) - dmin*m*sum(x); the sum
// order differs from the reference and is checked by the gate. Each thread
// accumulates `rr` rows for the same x values; the row sums are reduced by a
// shared-memory tree.
fn main_split(rr: u32, sg: u32, u: u32, nb: u32) -> String {
    let mut o = String::from(if sg == 1 { "\n" } else { "\nshared float partial[@RTR@];\n" });
    // One 8-byte unit of one row for every input column: 8 low-nibble and 8
    // high-nibble elements. A function (not inline code) gives the compiler
    // the better register allocation measured in EXP-04.
    let params: String = (0..nb).map(|c| format!(", vec4 xl0_{c}, vec4 xl1_{c}, vec4 xh0_{c}, vec4 xh1_{c}, float sl{c}, float sh{c}")).collect();
    let ret = if nb == 1 { "float" } else { "vec2" };
    o += &format!("\n{ret} q4unit(uint bi, uint c, uint h{params}) {{\n");
    o += "    vec2 dm = unpackHalf2x16(w[bi]);
    uint sc1; uint m1; uint sc2; uint m2;
    scale_min(bi, c * 2u, sc1, m1);
    scale_min(bi, c * 2u + 1u, sc2, m2);
    uint qb = bi + 4u + c * 8u + h * 2u;
    uint u0 = w[qb];
    uint u1 = w[qb + 1u];
    // Nibbles as bytes, converted by the 4x8 unpack (one convert per element); the
    // 1/255 normalization is undone by the 255 factor on the dot sums.
    vec4 ql0 = unpackUnorm4x8(u0 & 0x0F0F0F0Fu);
    vec4 ql1 = unpackUnorm4x8(u1 & 0x0F0F0F0Fu);
    vec4 qh0 = unpackUnorm4x8((u0 >> 4u) & 0x0F0F0F0Fu);
    vec4 qh1 = unpackUnorm4x8((u1 >> 4u) & 0x0F0F0F0Fu);
";
    for c in 0..nb {
        o += &format!(
            "    float r{c} = dm.x * float(sc1) * ((dot(ql0, xl0_{c}) + dot(ql1, xl1_{c})) * 255.0) - dm.y * float(m1) * sl{c}
              + dm.x * float(sc2) * ((dot(qh0, xh0_{c}) + dot(qh1, xh1_{c})) * 255.0) - dm.y * float(m2) * sh{c};
"
        );
    }
    o += &format!("    return {};\n}}\n", if nb == 1 { "r0".to_string() } else { "vec2(r0, r1)".to_string() });
    o += "
void main() {
    uint t = gl_LocalInvocationID.x;
    uint ly = gl_LocalInvocationID.y;
    uint row0 = (gl_WorkGroupID.x * @R@u + ly) * @RR@u;
    uint rmax = p.rows - 1u;
    uint xcol = p.blocks_per_row * 64u;
";
    for j in 0..rr {
        for c in 0..nb {
            o += &format!("    float sum{j}_{c} = 0.0;\n");
        }
    }
    // Legality guarantees blocks_per_row * 16 is a multiple of t * u, so the
    // loop body has no per-unit guards and its loads can be issued together.
    // With nb > 1 the weights of a unit are decoded once and applied to every
    // input column.
    o += "    uint units = p.blocks_per_row * 16u;\n    for (uint nb = t; nb < units; nb += @TU@u) {\n";
    for k in 0..u {
        o += &format!(
            "        uint n{k} = nb + {k}u * @T@u;
        uint b{k} = n{k} >> 4u;
        uint c{k} = (n{k} >> 2u) & 3u;
        uint h{k} = n{k} & 3u;
        uint xb{k} = ((b{k} * 256u + c{k} * 64u + h{k} * 8u) >> 2u);
"
        );
        for c in 0..nb {
            o += &format!(
                "        vec4 xl0_{k}_{c} = x4[xb{k} + {c}u * xcol];
        vec4 xl1_{k}_{c} = x4[xb{k} + 1u + {c}u * xcol];
        vec4 xh0_{k}_{c} = x4[xb{k} + 8u + {c}u * xcol];
        vec4 xh1_{k}_{c} = x4[xb{k} + 9u + {c}u * xcol];
        float sl{k}_{c} = dot(xl0_{k}_{c}, vec4(1.0)) + dot(xl1_{k}_{c}, vec4(1.0));
        float sh{k}_{c} = dot(xh0_{k}_{c}, vec4(1.0)) + dot(xh1_{k}_{c}, vec4(1.0));
"
            );
        }
    }
    for k in 0..u {
        for j in 0..rr {
            let xs: String = (0..nb).map(|c| format!(", xl0_{k}_{c}, xl1_{k}_{c}, xh0_{k}_{c}, xh1_{k}_{c}, sl{k}_{c}, sh{k}_{c}")).collect();
            let bi = format!("(min(row0 + {j}u, rmax) * p.blocks_per_row + b{k}) * 36u");
            if nb == 1 {
                o += &format!("        sum{j}_0 += q4unit({bi}, c{k}, h{k}{xs});\n");
            } else {
                o += &format!("        {{ vec2 r = q4unit({bi}, c{k}, h{k}{xs}); sum{j}_0 += r.x; sum{j}_1 += r.y; }}\n");
            }
        }
    }
    o += "    }\n";
    if sg == 1 {
        for j in 0..rr {
            for c in 0..nb {
                o += &format!("    float tot{j}_{c} = subgroupClusteredAdd(sum{j}_{c}, @T@u);\n");
            }
        }
        o += "    if (t == 0u) {\n";
        for j in 0..rr {
            for c in 0..nb {
                o += &format!("        if (row0 + {j}u < p.rows) {{ y[{c}u * p.rows + row0 + {j}u] = tot{j}_{c}; }}\n");
            }
        }
        o += "    }\n}\n";
        return o;
    }
    for j in 0..rr {
        for c in 0..nb {
            o += &format!("    partial[((ly * @RR@u + {j}u) * {nb}u + {c}u) * @T@u + t] = sum{j}_{c};\n");
        }
    }
    o += "    memoryBarrierShared();
    barrier();
    for (uint s = @T@u / 2u; s > 0u; s >>= 1u) {
        if (t < s) {
";
    for j in 0..rr {
        for c in 0..nb {
            o += &format!("            partial[((ly * @RR@u + {j}u) * {nb}u + {c}u) * @T@u + t] += partial[((ly * @RR@u + {j}u) * {nb}u + {c}u) * @T@u + t + s];\n");
        }
    }
    o += "        }
        memoryBarrierShared();
        barrier();
    }
    if (t == 0u) {
";
    for j in 0..rr {
        for c in 0..nb {
            o += &format!("        if (row0 + {j}u < p.rows) {{ y[{c}u * p.rows + row0 + {j}u] = partial[((ly * @RR@u + {j}u) * {nb}u + {c}u) * @T@u]; }}\n");
        }
    }
    o += "    }\n}\n";
    o
}
pub fn validate(s: &Q4kSchedule) -> Result<(), EmitError> {
    if s.t == 0 || !s.t.is_power_of_two() {
        return Err(EmitError::InvalidSchedule(format!("t={} must be a power of two", s.t)));
    }
    if s.r == 0 || !s.r.is_power_of_two() {
        return Err(EmitError::InvalidSchedule(format!("r={} must be a power of two", s.r)));
    }
    if s.invocations() > MAX_INVOCATIONS {
        return Err(EmitError::InvalidSchedule(format!("t*r={} exceeds {MAX_INVOCATIONS}", s.invocations())));
    }
    if !matches!(s.nb, 1 | 2) || (s.nb == 2 && (s.m != 1 || s.rr != 1)) || !matches!(s.u, 1 | 2 | 4) || (s.u != 1 && s.m != 1) || s.sg > 1 || (s.sg == 1 && s.m != 1) || s.rr == 0 || (s.m == 0 && s.rr != 1) || s.m > 1 || (s.m == 1 && (s.xv != 4 || s.t < 2)) {
        return Err(EmitError::InvalidSchedule(format!("mapping m={} needs xv=4 and t>=2", s.m)));
    }
    if s.xv != 1 && s.xv != 4 {
        return Err(EmitError::InvalidSchedule(format!("xv={} must be 1 or 4", s.xv)));
    }
    Ok(())
}

/// Emits the compute shader source for a schedule. Deterministic.
pub fn emit_q4k_matvec(s: &Q4kSchedule) -> Result<String, EmitError> {
    validate(s)?;
    let (lx, ly) = if s.t == 1 && s.m == 0 { (s.r, 1) } else { (s.t, s.r) };
    let split = main_split(s.rr, s.sg, s.u, s.nb);
    let body: &str = match (s.m, s.t) {
        (1, _) => &split,
        (_, 1) => MAIN_SERIAL,
        _ => MAIN_COOPERATIVE,
    };
    let (xdecl, loops) = if s.xv == 4 { (XDECL_VEC4, LOOPS_VEC4) } else { (XDECL_SCALAR, LOOPS_SCALAR) };
    let src = [COMMON, body].concat().replace("@XDECL@", xdecl).replace("@LOOPS@", loops);
    let src = if s.sg == 1 { src.replacen("#version 450\n", "#version 450\n#extension GL_KHR_shader_subgroup_clustered : enable\n", 1) } else { src };
    Ok(src
        .replace("@VERSION@", CODEGEN_VERSION)
        .replace("T=@T@ R=@R@", &format!("T={} R={} V={} M={} RR={} SG={} U={} NB={}", s.t, s.r, s.xv, s.m, s.rr, s.sg, s.u, s.nb))
        .replace("@KERNEL@", KERNEL_NAME)
        .replace("@LX@", &lx.to_string())
        .replace("@LY@", &ly.to_string())
        .replace("@RTR@", &(s.t * s.r * s.rr * s.nb).to_string())
        .replace("@TU@", &(s.t * s.u).to_string())
        .replace("@RT@", &(s.t * s.r).to_string())
        .replace("@RR@", &s.rr.to_string())
        .replace("@T@", &s.t.to_string())
        .replace("@R@", &s.r.to_string()))
}

/// Workgroup count for `rows` rows.
pub fn group_count(s: &Q4kSchedule, rows: u32) -> u32 {
    rows.div_ceil(s.r * s.rr)
}

/// Identity of an emitted kernel: schedule and generator version are part of
/// the source text, so the source digest alone keys the cache.
pub fn source_digest(src: &str) -> String {
    sha256_hex(src.as_bytes())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn serial_kernel_has_no_barrier_or_shared_memory() {
        let src = emit_q4k_matvec(&Q4kSchedule { t: 1, r: 8, xv: 1, m: 0, rr: 1, sg: 0, u: 1, nb: 1 }).unwrap();
        assert!(src.contains("local_size_x = 8, local_size_y = 1"));
        assert!(!src.contains("barrier()"));
        assert!(!src.contains("shared float"));
    }

    #[test]
    fn cooperative_kernel_has_reduction_and_sized_partials() {
        let src = emit_q4k_matvec(&Q4kSchedule { t: 4, r: 2, xv: 1, m: 0, rr: 1, sg: 0, u: 1, nb: 1 }).unwrap();
        assert!(src.contains("local_size_x = 4, local_size_y = 2"));
        assert!(src.contains("shared float partial[8];"));
        assert!(src.contains("barrier();"));
        assert!(src.contains("b += 4u"));
        assert!(!src.contains('@'), "unreplaced placeholder");
    }

    #[test]
    fn emission_is_deterministic_and_schedule_sensitive() {
        let a = emit_q4k_matvec(&Q4kSchedule { t: 2, r: 1, xv: 1, m: 0, rr: 1, sg: 0, u: 1, nb: 1 }).unwrap();
        let b = emit_q4k_matvec(&Q4kSchedule { t: 2, r: 1, xv: 1, m: 0, rr: 1, sg: 0, u: 1, nb: 1 }).unwrap();
        let c = emit_q4k_matvec(&Q4kSchedule { t: 4, r: 1, xv: 1, m: 0, rr: 1, sg: 0, u: 1, nb: 1 }).unwrap();
        assert_eq!(source_digest(&a), source_digest(&b));
        assert_ne!(source_digest(&a), source_digest(&c));
    }

    #[test]
    fn invalid_schedules_are_rejected() {
        for s in [
            Q4kSchedule { t: 0, r: 1, xv: 1, m: 0, rr: 1, sg: 0, u: 1, nb: 1 },
            Q4kSchedule { t: 3, r: 1, xv: 1, m: 0, rr: 1, sg: 0, u: 1, nb: 1 },
            Q4kSchedule { t: 1, r: 6, xv: 1, m: 0, rr: 1, sg: 0, u: 1, nb: 1 },
            Q4kSchedule { t: 64, r: 32, xv: 1, m: 0, rr: 1, sg: 0, u: 1, nb: 1 },
            Q4kSchedule { t: 2, r: 2, xv: 2, m: 0, rr: 1, sg: 0, u: 1, nb: 1 },
        ] {
            assert!(emit_q4k_matvec(&s).is_err(), "{s:?}");
        }
    }

    #[test]
    fn vec4_variant_loads_x_as_vec4_and_differs_from_scalar() {
        let v = emit_q4k_matvec(&Q4kSchedule { t: 2, r: 8, xv: 4, m: 0, rr: 1, sg: 0, u: 1, nb: 1 }).unwrap();
        let a = emit_q4k_matvec(&Q4kSchedule { t: 2, r: 8, xv: 1, m: 0, rr: 1, sg: 0, u: 1, nb: 1 }).unwrap();
        assert!(v.contains("vec4 x4[]") && !v.contains("float x[]"));
        assert!(a.contains("float x[]") && !a.contains("vec4 x4"));
        assert!(!v.contains('@') && v.contains("V=4"));
        assert_ne!(source_digest(&v), source_digest(&a));
    }

    #[test]
    fn split_mapping_emits_tree_reduction() {
        let src = emit_q4k_matvec(&Q4kSchedule { t: 64, r: 2, xv: 4, m: 1, rr: 1, sg: 0, u: 1, nb: 1 }).unwrap();
        assert!(src.contains("local_size_x = 64, local_size_y = 2") && src.contains("shared float partial[128];"));
        assert!(src.contains("s >>= 1u") && !src.contains('@'));
        assert!(emit_q4k_matvec(&Q4kSchedule { t: 64, r: 1, xv: 1, m: 1, rr: 1, sg: 0, u: 1, nb: 1 }).is_err());
    }

    #[test]
    fn group_count_rounds_up() {
        assert_eq!(group_count(&Q4kSchedule { t: 2, r: 4, xv: 1, m: 0, rr: 1, sg: 0, u: 1, nb: 1 }, 10), 3);
        assert_eq!(group_count(&Q4kSchedule { t: 1, r: 1, xv: 1, m: 0, rr: 1, sg: 0, u: 1, nb: 1 }, 7), 7);
    }
}
