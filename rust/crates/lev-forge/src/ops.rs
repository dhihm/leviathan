//! GLSL emitters for the non-matvec operations of the Ornith (qwen35) decode
//! step. Dimensions are baked into the source, so the kernel text (and its
//! cache key) identifies the exact shape. All activations are f32.
//!
//! These are deliberately simple one-workgroup-per-row kernels; the heavy
//! traffic is in the quantized matvecs. Per-token values (state selector,
//! position, rope tables) come from a `ctrl` buffer so one recorded command
//! buffer can be replayed for every step.
//!
//! Batching: `nb` input columns (1 or 2) are processed per step; column `c`
//! is the token at position `pos_base + c`. Recurrent state (conv and delta)
//! is kept in two buffers: after a step buffer 0 holds the state after column
//! 0 and buffer 1 the state after the last column. The next step reads the one
//! selected by `ctrl[0]`, so a rejected speculative column costs no copy.
//!
//! `ctrl` words: `[0]` state selector, `[1]` position of column 0, then for
//! column `c` at `2 + c*64`: `cos[0..32]` and `sin[0..32]` as f32 bits.

pub const OPS_VERSION: &str = "opsgen-glsl-v2";
pub const CTRL_WORDS_PER_COL: usize = 64;
/// Columns per prefill chunk.
pub const CHUNK_COLS: usize = 8;

fn finish(src: &str, vars: &[(&str, String)]) -> String {
    let mut s = src.replace("@VERSION@", OPS_VERSION);
    for (k, v) in vars {
        s = s.replace(&format!("@{k}@"), v);
    }
    assert!(!s.contains('@'), "unreplaced placeholder in generated source");
    s
}

const HEAD: &str = "#version 450\n// Generated by lev-forge (@VERSION@)\n";

/// `y[g*D + i] = x[g*D + i] * rsqrt(mean(x_g^2) + eps) * w[i]` for each of the
/// workgroups' rows `g`. Bindings: 0 x, 1 w, 2 y.
pub fn rmsnorm(dim: usize, eps: f32) -> String {
    let body = r#"layout(local_size_x = 256) in;
layout(std430, set = 0, binding = 0) readonly buffer X { float x[]; };
layout(std430, set = 0, binding = 1) readonly buffer W { float w[]; };
layout(std430, set = 0, binding = 2) writeonly buffer Y { float y[]; };
shared float red[256];
void main() {
    uint g = gl_WorkGroupID.x;
    uint t = gl_LocalInvocationID.x;
    float s = 0.0;
    for (uint i = t; i < @D@u; i += 256u) { float v = x[g * @D@u + i]; s += v * v; }
    red[t] = s;
    barrier();
    for (uint k = 128u; k > 0u; k >>= 1u) {
        if (t < k) { red[t] += red[t + k]; }
        barrier();
    }
    float inv = 1.0 / sqrt(red[0] / float(@D@) + @EPS@);
    for (uint i = t; i < @D@u; i += 256u) { y[g * @D@u + i] = x[g * @D@u + i] * inv * w[i]; }
}
"#;
    finish(&[HEAD, body].concat(), &[("D", dim.to_string()), ("EPS", format!("{:e}", eps))])
}

/// `x[i] += d[i]`, `n` a multiple of 256. Bindings: 0 x (read-write), 1 d.
pub fn add_inplace() -> String {
    let body = r#"layout(local_size_x = 256) in;
layout(std430, set = 0, binding = 0) buffer X { float x[]; };
layout(std430, set = 0, binding = 1) readonly buffer D { float d[]; };
void main() { uint i = gl_GlobalInvocationID.x; x[i] += d[i]; }
"#;
    finish(&[HEAD, body].concat(), &[])
}

/// `act[i] = silu(gate[i]) * up[i]`. Bindings: 0 gate, 1 up, 2 act.
pub fn swiglu() -> String {
    let body = r#"layout(local_size_x = 256) in;
layout(std430, set = 0, binding = 0) readonly buffer G { float g[]; };
layout(std430, set = 0, binding = 1) readonly buffer U { float u[]; };
layout(std430, set = 0, binding = 2) writeonly buffer A { float a[]; };
void main() { uint i = gl_GlobalInvocationID.x; float v = g[i]; a[i] = v / (1.0 + exp(-v)) * u[i]; }
"#;
    finish(&[HEAD, body].concat(), &[])
}

/// `dst[i] = src[i]`, a multiple of 256 elements. Bindings: 0 src, 1 dst.
pub fn copy() -> String {
    let body = r#"layout(local_size_x = 256) in;
layout(std430, set = 0, binding = 0) readonly buffer S { float s[]; };
layout(std430, set = 0, binding = 1) writeonly buffer D { float d[]; };
void main() { uint i = gl_GlobalInvocationID.x; d[i] = s[i]; }
"#;
    finish(&[HEAD, body].concat(), &[])
}

/// Causal depthwise conv (kernel `k`) over `cd` channels with a `k-1` deep
/// state, followed by SiLU, for `nb` consecutive columns. One thread per
/// channel. Bindings: 0 input `[nb][cd]`, 1 state buffer 0, 2 state buffer 1,
/// 3 weights `[cd][k]`, 4 output `[nb][cd]`, 5 ctrl, 6 state buffer 2 (`nb = 3`
/// only; then `ctrl[0]` is the index 0..2 of the buffer holding the valid state).
pub fn ssm_conv(cd: usize, k: usize, nb: usize) -> String {
    assert!((1..=3).contains(&nb));
    let mut body = String::from(
        r#"layout(local_size_x = 256) in;
layout(std430, set = 0, binding = 0) readonly buffer In { float xin[]; };
layout(std430, set = 0, binding = 1) buffer S0 { float st0[]; };
layout(std430, set = 0, binding = 2) buffer S1 { float st1[]; };
layout(std430, set = 0, binding = 3) readonly buffer W { float w[]; };
layout(std430, set = 0, binding = 4) writeonly buffer Out { float o[]; };
layout(std430, set = 0, binding = 5) readonly buffer Ctrl { uint ctrl[]; };
void main() {
    uint c = gl_GlobalInvocationID.x;
    float s[@KM1@];
    bool sel = ctrl[0] != 0u;
    for (uint i = 0u; i < @KM1@u; i++) { s[i] = sel ? st1[i * @CD@u + c] : st0[i * @CD@u + c]; }
"#,
    );
    if nb == 3 {
        // Three states: a counter replaces the flag, and binding 6 is the third buffer.
        body = body.replace(
            "layout(std430, set = 0, binding = 5) readonly buffer Ctrl { uint ctrl[]; };",
            "layout(std430, set = 0, binding = 5) readonly buffer Ctrl { uint ctrl[]; };\nlayout(std430, set = 0, binding = 6) buffer S2 { float st2[]; };",
        );
        body = body.replace("bool sel = ctrl[0] != 0u;", "uint sel = ctrl[0];");
        body = body.replace(
            "s[i] = sel ? st1[i * @CD@u + c] : st0[i * @CD@u + c];",
            "s[i] = sel == 2u ? st2[i * @CD@u + c] : (sel == 1u ? st1[i * @CD@u + c] : st0[i * @CD@u + c]);",
        );
    }
    for col in 0..nb {
        body += &format!(
            "    {{
        float cur = xin[{col}u * @CD@u + c];
        float acc = 0.0;
        for (uint i = 0u; i < @KM1@u; i++) {{ acc += s[i] * w[c * @K@u + i]; }}
        acc += cur * w[c * @K@u + @KM1@u];
        o[{col}u * @CD@u + c] = acc / (1.0 + exp(-acc));
        for (uint i = 0u; i + 1u < @KM1@u; i++) {{ s[i] = s[i + 1u]; }}
        s[@KM1@u - 1u] = cur;
        for (uint i = 0u; i < @KM1@u; i++) {{ st{col}[i * @CD@u + c] = s[i]; }}
    }}
"
        );
    }
    body += "}\n";
    finish(&[HEAD, &body].concat(), &[("CD", cd.to_string()), ("K", k.to_string()), ("KM1", (k - 1).to_string())])
}

/// L2-normalizes the q (groups `0..kh`) and k (`kh..2kh`) heads of each column's
/// conv output and scales q by `1/sqrt(hs)`. Workgroups: `nb * 2 * kh`.
/// Bindings: 0 conv output `[nb][cd]`, 1 normalized qk `[nb][2*kh*hs]`.
pub fn ssm_qk_norm(kh: usize, hs: usize, cd: usize) -> String {
    let body = r#"layout(local_size_x = @HS@) in;
layout(std430, set = 0, binding = 0) readonly buffer In { float xin[]; };
layout(std430, set = 0, binding = 1) writeonly buffer Out { float o[]; };
shared float red[@HS@];
void main() {
    uint wg = gl_WorkGroupID.x;
    uint col = wg / (2u * @KH@u);
    uint g = wg % (2u * @KH@u);
    uint t = gl_LocalInvocationID.x;
    float v = xin[col * @CD@u + g * @HS@u + t];
    red[t] = v * v;
    barrier();
    for (uint k = @HS@u / 2u; k > 0u; k >>= 1u) {
        if (t < k) { red[t] += red[t + k]; }
        barrier();
    }
    float inv = 1.0 / max(sqrt(red[0]), 1e-6);
    float scale = (g < @KH@u) ? inversesqrt(float(@HS@)) : 1.0;
    o[col * 2u * @KH@u * @HS@u + g * @HS@u + t] = v * inv * scale;
}
"#;
    finish(&[HEAD, body].concat(), &[("HS", hs.to_string()), ("KH", kh.to_string()), ("CD", cd.to_string())])
}

/// Gated-delta-rule steps for every value head (workgroup per head, thread per
/// value index) and `nb` columns, each followed by the gated RMS norm. The
/// state is `[head][key i][value j]` so threads read contiguous values. The
/// old state is read from the buffer selected by `ctrl[0]`; buffer 0 receives
/// the state after column 0 and buffer 1 the state after column `nb-1`.
/// Bindings: 0 qk, 1 conv output (v at offset `2*kh*hs` of each column),
/// 2 alpha `[nb][vh]`, 3 beta (pre-sigmoid) `[nb][vh]`, 4 dt bias, 5 a,
/// 6 state buffer 0, 7 state buffer 1, 8 z `[nb][vh*hs]`, 9 norm weight `[hs]`,
/// 10 output `[nb][vh*hs]`, 11 ctrl.
pub fn ssm_delta(kh: usize, vh: usize, hs: usize, eps: f32, cd: usize, nb: usize) -> String {
    assert!(vh % kh == 0 && (1..=3).contains(&nb));
    let mut body = String::from(
        r#"layout(local_size_x = @HS@) in;
layout(std430, set = 0, binding = 0) readonly buffer QK { float qk[]; };
layout(std430, set = 0, binding = 1) readonly buffer Conv { float cv[]; };
layout(std430, set = 0, binding = 2) readonly buffer Alpha { float alpha[]; };
layout(std430, set = 0, binding = 3) readonly buffer Beta { float beta_raw[]; };
layout(std430, set = 0, binding = 4) readonly buffer Dt { float dt[]; };
layout(std430, set = 0, binding = 5) readonly buffer A { float a[]; };
layout(std430, set = 0, binding = 6) buffer S0 { float st0[]; };
layout(std430, set = 0, binding = 7) buffer S1 { float st1[]; };
layout(std430, set = 0, binding = 8) readonly buffer Z { float z[]; };
layout(std430, set = 0, binding = 9) readonly buffer NW { float nw[]; };
layout(std430, set = 0, binding = 10) writeonly buffer Out { float o[]; };
layout(std430, set = 0, binding = 11) readonly buffer Ctrl { uint ctrl[]; };
shared float kq[@KQ@];
shared float red[@HS@];
float softplus(float x) { return x > 20.0 ? x : log(1.0 + exp(x)); }
void main() {
    uint h = gl_WorkGroupID.x;
    uint j = gl_LocalInvocationID.x;
    uint kh = h % @KH@u;
    bool sel = ctrl[0] != 0u;
    uint base = h * @HS@u * @HS@u;
"#,
    );
    for c in 0..nb {
        body += &format!(
            "    kq[{c}u * 2u * @HS@u + j] = qk[{c}u * 2u * @KH@u * @HS@u + (@KH@u + kh) * @HS@u + j];
    kq[{c}u * 2u * @HS@u + @HS@u + j] = qk[{c}u * 2u * @KH@u * @HS@u + kh * @HS@u + j];
    float decay{c} = exp(softplus(alpha[{c}u * @VH@u + h] + dt[h]) * a[h]);
    float beta{c} = 1.0 / (1.0 + exp(-beta_raw[{c}u * @VH@u + h]));
    float v{c} = cv[{c}u * @CD@u + 2u * @KH@u * @HS@u + h * @HS@u + j];
"
        );
    }
    body += "    barrier();\n";
    // With three states the selector is an index and binding 12 is the third buffer.
    if nb == 3 {
        body = body.replace(
            "layout(std430, set = 0, binding = 11) readonly buffer Ctrl { uint ctrl[]; };",
            "layout(std430, set = 0, binding = 11) readonly buffer Ctrl { uint ctrl[]; };\nlayout(std430, set = 0, binding = 12) buffer S2 { float st2[]; };",
        );
        body = body.replace("bool sel = ctrl[0] != 0u;", "uint sel = ctrl[0];");
    }
    let old = if nb == 3 {
        "(sel == 2u ? st2[base + i * @HS@u + j] : (sel == 1u ? st1[base + i * @HS@u + j] : st0[base + i * @HS@u + j]))"
    } else {
        "(sel ? st1[base + i * @HS@u + j] : st0[base + i * @HS@u + j])"
    };
    // Pass 1: kv for column 0 from the old state.
    body += &"    float kv0 = 0.0;
    for (uint i = 0u; i < @HS@u; i++) {
        float so = @OLD@;
        kv0 += so * decay0 * kq[i];
    }
    float delta0 = beta0 * (v0 - kv0);
    float acc0 = 0.0;
"
    .replace("@OLD@", old);
    if nb == 1 {
        body += &"    for (uint i = 0u; i < @HS@u; i++) {
        float so = @OLD@;
        float s = so * decay0 + kq[i] * delta0;
        st0[base + i * @HS@u + j] = s;
        acc0 += s * kq[@HS@u + i];
    }
"
        .replace("@OLD@", old);
    } else {
        // Pass 2: state after column 0 (written to buffer 0), output 0, kv for column 1.
        body += &"    float kv1 = 0.0;
    for (uint i = 0u; i < @HS@u; i++) {
        float so = @OLD@;
        float s = so * decay0 + kq[i] * delta0;
        st0[base + i * @HS@u + j] = s;
        acc0 += s * kq[@HS@u + i];
        kv1 += s * decay1 * kq[2u * @HS@u + i];
    }
    float delta1 = beta1 * (v1 - kv1);
    float acc1 = 0.0;
"
        .replace("@OLD@", old);
        if nb == 2 {
            body += "    for (uint i = 0u; i < @HS@u; i++) {
        float s = st0[base + i * @HS@u + j] * decay1 + kq[2u * @HS@u + i] * delta1;
        st1[base + i * @HS@u + j] = s;
        acc1 += s * kq[3u * @HS@u + i];
    }
";
        } else {
            // Pass 3: state after column 1 (buffer 1), output 1, kv for column 2; pass 4: state after column 2 (buffer 2).
            body += "    float kv2 = 0.0;
    for (uint i = 0u; i < @HS@u; i++) {
        float s = st0[base + i * @HS@u + j] * decay1 + kq[2u * @HS@u + i] * delta1;
        st1[base + i * @HS@u + j] = s;
        acc1 += s * kq[3u * @HS@u + i];
        kv2 += s * decay2 * kq[4u * @HS@u + i];
    }
    float delta2 = beta2 * (v2 - kv2);
    float acc2 = 0.0;
    for (uint i = 0u; i < @HS@u; i++) {
        float s = st1[base + i * @HS@u + j] * decay2 + kq[4u * @HS@u + i] * delta2;
        st2[base + i * @HS@u + j] = s;
        acc2 += s * kq[5u * @HS@u + i];
    }
";
        }
    }
    for c in 0..nb {
        body += &format!(
            "    red[j] = acc{c} * acc{c};
    barrier();
    for (uint k = @HS@u / 2u; k > 0u; k >>= 1u) {{
        if (j < k) {{ red[j] += red[j + k]; }}
        barrier();
    }}
    {{
        float inv = 1.0 / sqrt(red[0] / float(@HS@) + @EPS@);
        float zz = z[{c}u * @VH@u * @HS@u + h * @HS@u + j];
        o[{c}u * @VH@u * @HS@u + h * @HS@u + j] = acc{c} * inv * nw[j] * (zz / (1.0 + exp(-zz)));
    }}
    barrier();
"
        );
    }
    body += "}\n";
    finish(
        &[HEAD, &body].concat(),
        &[
            ("HS", hs.to_string()),
            ("KQ", (nb * 2 * hs).to_string()),
            ("KH", kh.to_string()),
            ("VH", vh.to_string()),
            ("CD", cd.to_string()),
            ("EPS", format!("{:e}", eps)),
        ],
    )
}

/// Per-head q/k RMS norm plus rope, writes q to `q_out` and k/v into the KV
/// cache at each column's position. Workgroups per column: `nh` q heads, then
/// `nkv` k heads, then `nkv` v heads (`nb` times that). Bindings: 0 qfull
/// `[nb][nh][q hd | gate hd]`, 1 k `[nb][nkv*hd]`, 2 v, 3 q norm weight,
/// 4 k norm weight, 5 q out `[nb][nh*hd]`, 6 k cache, 7 v cache, 8 ctrl.
pub fn attn_prep(nh: usize, nkv: usize, hd: usize, rope_dim: usize, eps: f32) -> String {
    let body = r#"layout(local_size_x = @HD@) in;
layout(std430, set = 0, binding = 0) readonly buffer QF { float qfull[]; };
layout(std430, set = 0, binding = 1) readonly buffer K { float kin[]; };
layout(std430, set = 0, binding = 2) readonly buffer V { float vin[]; };
layout(std430, set = 0, binding = 3) readonly buffer QN { float qn[]; };
layout(std430, set = 0, binding = 4) readonly buffer KN { float kn[]; };
layout(std430, set = 0, binding = 5) writeonly buffer QO { float qo[]; };
layout(std430, set = 0, binding = 6) buffer KC { float kc[]; };
layout(std430, set = 0, binding = 7) buffer VC { float vc[]; };
layout(std430, set = 0, binding = 8) readonly buffer Ctrl { uint ctrl[]; };
shared float red[@HD@];
shared float buf[@HD@];
void main() {
    uint wg = gl_WorkGroupID.x;
    uint col = wg / (@NH@u + 2u * @NKV@u);
    uint hh = wg % (@NH@u + 2u * @NKV@u);
    uint t = gl_LocalInvocationID.x;
    uint pos = ctrl[1] + col;
    uint cbase = 2u + col * 64u;
    if (hh >= @NH@u + @NKV@u) {
        uint kvh = hh - @NH@u - @NKV@u;
        vc[(pos * @NKV@u + kvh) * @HD@u + t] = vin[col * @NKV@u * @HD@u + kvh * @HD@u + t];
        return;
    }
    bool isq = hh < @NH@u;
    float val = isq ? qfull[col * @NH@u * @HD2@u + hh * @HD2@u + t] : kin[col * @NKV@u * @HD@u + (hh - @NH@u) * @HD@u + t];
    red[t] = val * val;
    barrier();
    for (uint k = @HD@u / 2u; k > 0u; k >>= 1u) {
        if (t < k) { red[t] += red[t + k]; }
        barrier();
    }
    float inv = 1.0 / sqrt(red[0] / float(@HD@) + @EPS@);
    buf[t] = val * inv * (isq ? qn[t] : kn[t]);
    barrier();
    float outv = buf[t];
    if (t < @RD@u) {
        uint i = t % @RH@u;
        float c = uintBitsToFloat(ctrl[cbase + i]);
        float s = uintBitsToFloat(ctrl[cbase + @RH@u + i]);
        float a = buf[i];
        float b = buf[i + @RH@u];
        outv = t < @RH@u ? a * c - b * s : a * s + b * c;
    }
    if (isq) { qo[col * @NH@u * @HD@u + hh * @HD@u + t] = outv; }
    else { kc[(pos * @NKV@u + (hh - @NH@u)) * @HD@u + t] = outv; }
}
"#;
    assert!(rope_dim / 2 <= 32, "ctrl rope table holds 32 pairs per column");
    finish(
        &[HEAD, body].concat(),
        &[
            ("HD", hd.to_string()),
            ("HD2", (2 * hd).to_string()),
            ("NH", nh.to_string()),
            ("NKV", nkv.to_string()),
            ("RD", rope_dim.to_string()),
            ("RH", (rope_dim / 2).to_string()),
            ("EPS", format!("{:e}", eps)),
        ],
    )
}

/// Attention for each column over its cached positions (workgroup per
/// column and q head, thread per head dimension), then the sigmoid output
/// gate. Column `c` attends to `ctrl[1] + c + 1` positions. Bindings: 0 q,
/// 1 k cache, 2 v cache, 3 qfull (gate), 4 out `[nb][nh*hd]`, 5 ctrl.
/// `ctx` bounds the positions held in shared memory.
pub fn attn_decode(nh: usize, nkv: usize, hd: usize, ctx: usize) -> String {
    let body = r#"layout(local_size_x = @HD@) in;
layout(std430, set = 0, binding = 0) readonly buffer Q { float q[]; };
layout(std430, set = 0, binding = 1) readonly buffer KC { float kc[]; };
layout(std430, set = 0, binding = 2) readonly buffer VC { float vc[]; };
layout(std430, set = 0, binding = 3) readonly buffer QF { float qfull[]; };
layout(std430, set = 0, binding = 4) writeonly buffer O { float o[]; };
layout(std430, set = 0, binding = 5) readonly buffer Ctrl { uint ctrl[]; };
shared float qh[@HD@];
shared float sc[@CTX@];
shared float red[@HD@];
void main() {
    uint wg = gl_WorkGroupID.x;
    uint col = wg / @NH@u;
    uint h = wg % @NH@u;
    uint t = gl_LocalInvocationID.x;
    uint kvh = h / @GROUP@u;
    uint n = ctrl[1] + col + 1u;
    qh[t] = q[col * @NH@u * @HD@u + h * @HD@u + t];
    barrier();
    float m = -3.0e38;
    for (uint p = t; p < n; p += @HD@u) {
        uint base = (p * @NKV@u + kvh) * @HD@u;
        float s = 0.0;
        for (uint d = 0u; d < @HD@u; d++) { s += qh[d] * kc[base + d]; }
        s *= @SCALE@;
        sc[p] = s;
        m = max(m, s);
    }
    red[t] = m;
    barrier();
    for (uint k = @HD@u / 2u; k > 0u; k >>= 1u) {
        if (t < k) { red[t] = max(red[t], red[t + k]); }
        barrier();
    }
    float mx = red[0];
    barrier();
    float sum = 0.0;
    for (uint p = t; p < n; p += @HD@u) {
        float e = exp(sc[p] - mx);
        sc[p] = e;
        sum += e;
    }
    red[t] = sum;
    barrier();
    for (uint k = @HD@u / 2u; k > 0u; k >>= 1u) {
        if (t < k) { red[t] += red[t + k]; }
        barrier();
    }
    float total = red[0];
    float acc = 0.0;
    for (uint p = 0u; p < n; p++) { acc += sc[p] * vc[(p * @NKV@u + kvh) * @HD@u + t]; }
    float gate = qfull[col * @NH@u * @HD2@u + h * @HD2@u + @HD@u + t];
    o[col * @NH@u * @HD@u + h * @HD@u + t] = acc / total * (1.0 / (1.0 + exp(-gate)));
}
"#;
    finish(
        &[HEAD, body].concat(),
        &[
            ("HD", hd.to_string()),
            ("HD2", (2 * hd).to_string()),
            ("NH", nh.to_string()),
            ("NKV", nkv.to_string()),
            ("GROUP", (nh / nkv).to_string()),
            ("CTX", ctx.to_string()),
            ("SCALE", format!("{:e}", 1.0 / (hd as f32).sqrt())),
        ],
    )
}

/// Greedy token choice: workgroup `c` scans column `c` of `logits`
/// (`vocab` floats each) and writes the index of its maximum (lowest index on
/// ties) to `out[c]`, and the gap to the second best to `margin[c]`.
/// Bindings: 0 logits, 1 out (uint), 2 margin (float).
pub fn argmax(vocab: usize) -> String {
    let body = r#"layout(local_size_x = 1024) in;
layout(std430, set = 0, binding = 0) readonly buffer L { float l[]; };
layout(std430, set = 0, binding = 1) writeonly buffer O { uint o[]; };
layout(std430, set = 0, binding = 2) writeonly buffer M { float m[]; };
shared float sv[1024];
shared uint si[1024];
shared float s2[1024];
void main() {
    uint c = gl_WorkGroupID.x;
    uint t = gl_LocalInvocationID.x;
    float best = -3.0e38;
    float second = -3.0e38;
    uint bi = 0u;
    for (uint i = t; i < @V@u; i += 1024u) {
        float v = l[c * @V@u + i];
        if (v > best) { second = best; best = v; bi = i; }
        else if (v > second) { second = v; }
    }
    sv[t] = best; si[t] = bi; s2[t] = second;
    barrier();
    for (uint k = 512u; k > 0u; k >>= 1u) {
        if (t < k) {
            float ov = sv[t + k]; uint oi = si[t + k]; float o2 = s2[t + k];
            float mv = sv[t]; uint mi = si[t]; float m2 = s2[t];
            bool take = ov > mv || (ov == mv && oi < mi);
            float nb = take ? ov : mv;
            uint ni = take ? oi : mi;
            float other = take ? max(mv, o2) : max(ov, m2);
            sv[t] = nb; si[t] = ni; s2[t] = max(other, take ? m2 : o2);
        }
        barrier();
    }
    if (t == 0u) { o[c] = si[0]; m[c] = sv[0] - s2[0]; }
}
"#;
    finish(&[HEAD, body].concat(), &[("V", vocab.to_string())])
}

/// Embedding lookup from a Q4_K table: column `c` of `out` (`dim` floats) is
/// row `tok[c]`. Workgroup = one 256-element block; `nb * dim/256` groups.
/// Bindings: 0 table (uint words), 1 tok (uint), 2 out.
pub fn embed_q4k(dim: usize) -> String {
    let body = r#"layout(local_size_x = 256) in;
layout(std430, set = 0, binding = 0) readonly buffer W { uint w[]; };
layout(std430, set = 0, binding = 1) readonly buffer T { uint tok[]; };
layout(std430, set = 0, binding = 2) writeonly buffer O { float o[]; };
uint sbyte(uint bi, uint k) { return (w[bi + 1u + (k >> 2u)] >> ((k & 3u) * 8u)) & 255u; }
void scale_min(uint bi, uint j, out uint sc, out uint m) {
    if (j < 4u) { sc = sbyte(bi, j) & 63u; m = sbyte(bi, j + 4u) & 63u; }
    else {
        sc = (sbyte(bi, j + 4u) & 15u) | ((sbyte(bi, j - 4u) >> 6u) << 4u);
        m = (sbyte(bi, j + 4u) >> 4u) | ((sbyte(bi, j) >> 6u) << 4u);
    }
}
void main() {
    uint wg = gl_WorkGroupID.x;
    uint bpr = @D@u / 256u;
    uint col = wg / bpr;
    uint b = wg % bpr;
    uint t = gl_LocalInvocationID.x;
    uint bi = (tok[col] * bpr + b) * 36u;
    vec2 dm = unpackHalf2x16(w[bi]);
    uint chunk = t >> 6u;
    uint within = t & 63u;
    bool high = within >= 32u;
    uint l = within & 31u;
    uint sc; uint m;
    scale_min(bi, chunk * 2u + (high ? 1u : 0u), sc, m);
    uint byteoff = 16u + chunk * 32u + l;
    uint q = (w[bi + (byteoff >> 2u)] >> ((byteoff & 3u) * 8u)) & 255u;
    q = high ? (q >> 4u) : (q & 15u);
    o[col * @D@u + b * 256u + t] = dm.x * float(sc) * float(q) - dm.y * float(m);
}
"#;
    finish(&[HEAD, body].concat(), &[("D", dim.to_string())])
}

/// Chunk variant of `ssm_conv` for prefill: `nb` consecutive columns are
/// convolved in order, the state is read from the buffer selected by
/// `ctrl[0]` and only the final state is written, to buffer 0.
/// Bindings as `ssm_conv`.
pub fn ssm_conv_chunk(cd: usize, k: usize, nb: usize) -> String {
    let body = r#"layout(local_size_x = 256) in;
layout(std430, set = 0, binding = 0) readonly buffer In { float xin[]; };
layout(std430, set = 0, binding = 1) buffer S0 { float st0[]; };
layout(std430, set = 0, binding = 2) buffer S1 { float st1[]; };
layout(std430, set = 0, binding = 3) readonly buffer W { float w[]; };
layout(std430, set = 0, binding = 4) writeonly buffer Out { float o[]; };
layout(std430, set = 0, binding = 5) readonly buffer Ctrl { uint ctrl[]; };
void main() {
    uint c = gl_GlobalInvocationID.x;
    float s[@KM1@];
    bool sel = ctrl[0] != 0u;
    for (uint i = 0u; i < @KM1@u; i++) { s[i] = sel ? st1[i * @CD@u + c] : st0[i * @CD@u + c]; }
    for (uint col = 0u; col < @NB@u; col++) {
        float cur = xin[col * @CD@u + c];
        float acc = 0.0;
        for (uint i = 0u; i < @KM1@u; i++) { acc += s[i] * w[c * @K@u + i]; }
        acc += cur * w[c * @K@u + @KM1@u];
        o[col * @CD@u + c] = acc / (1.0 + exp(-acc));
        for (uint i = 0u; i + 1u < @KM1@u; i++) { s[i] = s[i + 1u]; }
        s[@KM1@u - 1u] = cur;
    }
    for (uint i = 0u; i < @KM1@u; i++) { st0[i * @CD@u + c] = s[i]; }
}
"#;
    finish(&[HEAD, body].concat(), &[("CD", cd.to_string()), ("K", k.to_string()), ("KM1", (k - 1).to_string()), ("NB", nb.to_string())])
}
/// Chunk variant of `ssm_delta` for prefill: the state column of a value index
/// (`hs` floats) stays in registers across the `nb` columns; it is read once
/// from the buffer selected by `ctrl[0]` and written once, to buffer 0. Two
/// adjacent lanes share one value index and hold half of the key range each
/// (so a lane needs `hs / 2` registers instead of `hs`, which fit without
/// spilling); their partial sums are combined with a lane exchange.
/// Workgroup size is `2 * hs`. Bindings as `ssm_delta`.
pub fn ssm_delta_chunk(kh: usize, vh: usize, hs: usize, eps: f32, cd: usize, nb: usize) -> String {
    assert!(vh % kh == 0);
    let body = r#"#extension GL_EXT_control_flow_attributes : enable
#extension GL_KHR_shader_subgroup_basic : enable
#extension GL_KHR_shader_subgroup_shuffle : enable
layout(local_size_x = @HS2@) in;
layout(std430, set = 0, binding = 0) readonly buffer QK { float qk[]; };
layout(std430, set = 0, binding = 1) readonly buffer Conv { float cv[]; };
layout(std430, set = 0, binding = 2) readonly buffer Alpha { float alpha[]; };
layout(std430, set = 0, binding = 3) readonly buffer Beta { float beta_raw[]; };
layout(std430, set = 0, binding = 4) readonly buffer Dt { float dt[]; };
layout(std430, set = 0, binding = 5) readonly buffer A { float a[]; };
layout(std430, set = 0, binding = 6) buffer S0 { float st0[]; };
layout(std430, set = 0, binding = 7) buffer S1 { float st1[]; };
layout(std430, set = 0, binding = 8) readonly buffer Z { float z[]; };
layout(std430, set = 0, binding = 9) readonly buffer NW { float nw[]; };
layout(std430, set = 0, binding = 10) writeonly buffer Out { float o[]; };
layout(std430, set = 0, binding = 11) readonly buffer Ctrl { uint ctrl[]; };
shared float kq[@HS2@];
shared float red[@HS@];
float softplus(float x) { return x > 20.0 ? x : log(1.0 + exp(x)); }
void main() {
    uint h = gl_WorkGroupID.x;
    uint t = gl_LocalInvocationID.x;
    uint j = t >> 1u;
    uint hf = t & 1u;
    uint ib = hf * (@HS@u / 2u);
    uint kh = h % @KH@u;
    bool sel = ctrl[0] != 0u;
    uint base = h * @HS@u * @HS@u;
    float s[@HALF@];
    [[unroll]] for (uint i = 0u; i < @HALF@u; i++) { s[i] = sel ? st1[base + (ib + i) * @HS@u + j] : st0[base + (ib + i) * @HS@u + j]; }
    for (uint c = 0u; c < @NB@u; c++) {
        // The first hs entries of kq are k, the next hs are q.
        kq[t] = t < @HS@u ? qk[c * 2u * @KH@u * @HS@u + (@KH@u + kh) * @HS@u + t]
                          : qk[c * 2u * @KH@u * @HS@u + kh * @HS@u + (t - @HS@u)];
        float decay = exp(softplus(alpha[c * @VH@u + h] + dt[h]) * a[h]);
        float beta = 1.0 / (1.0 + exp(-beta_raw[c * @VH@u + h]));
        float v = cv[c * @CD@u + 2u * @KH@u * @HS@u + h * @HS@u + j];
        barrier();
        float kv = 0.0;
        [[unroll]] for (uint i = 0u; i < @HALF@u; i++) { kv += s[i] * decay * kq[ib + i]; }
        kv += subgroupShuffleXor(kv, 1u);
        float delta = beta * (v - kv);
        float acc = 0.0;
        [[unroll]] for (uint i = 0u; i < @HALF@u; i++) {
            s[i] = s[i] * decay + kq[ib + i] * delta;
            acc += s[i] * kq[@HS@u + ib + i];
        }
        acc += subgroupShuffleXor(acc, 1u);
        if (hf == 0u) { red[j] = acc * acc; }
        barrier();
        for (uint k = @HS@u / 2u; k > 0u; k >>= 1u) {
            if (t < k) { red[t] += red[t + k]; }
            barrier();
        }
        float inv = 1.0 / sqrt(red[0] / float(@HS@) + @EPS@);
        float zz = z[c * @VH@u * @HS@u + h * @HS@u + j];
        if (hf == 0u) { o[c * @VH@u * @HS@u + h * @HS@u + j] = acc * inv * nw[j] * (zz / (1.0 + exp(-zz))); }
        barrier();
    }
    [[unroll]] for (uint i = 0u; i < @HALF@u; i++) { st0[base + (ib + i) * @HS@u + j] = s[i]; }
}
"#;
    finish(
        &[HEAD, body].concat(),
        &[
            ("HS", hs.to_string()),
            ("HS2", (2 * hs).to_string()),
            ("HALF", (hs / 2).to_string()),
            ("KH", kh.to_string()),
            ("VH", vh.to_string()),
            ("CD", cd.to_string()),
            ("EPS", format!("{:e}", eps)),
            ("NB", nb.to_string()),
        ],
    )
}
/// `dst[col * stride + off + i] = src[col * dim + i]` for `nb` columns (one
/// thread per element, `nb * dim` threads). Bindings: 0 src, 1 dst.
pub fn copy_cols(dim: usize, stride: usize, off: usize) -> String {
    let body = r#"layout(local_size_x = 256) in;
layout(std430, set = 0, binding = 0) readonly buffer S { float s[]; };
layout(std430, set = 0, binding = 1) writeonly buffer D { float d[]; };
void main() {
    uint g = gl_GlobalInvocationID.x;
    uint col = g / @DIM@u;
    uint i = g % @DIM@u;
    d[col * @STRIDE@u + @OFF@u + i] = s[g];
}
"#;
    finish(&[HEAD, body].concat(), &[("DIM", dim.to_string()), ("STRIDE", stride.to_string()), ("OFF", off.to_string())])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_op_emits_without_placeholders() {
        let mut srcs = vec![copy_cols(4096, 8192, 4096), ssm_conv_chunk(8192, 4, 8), ssm_delta_chunk(16, 32, 128, 1e-6, 8192, 8), argmax(248320), embed_q4k(4096), rmsnorm(4096, 1e-6), add_inplace(), swiglu(), copy(), ssm_qk_norm(16, 128, 8192), attn_prep(16, 4, 256, 64, 1e-6), attn_decode(16, 4, 256, 4096)];
        for nb in 1..=2 {
            srcs.push(ssm_conv(8192, 4, nb));
            srcs.push(ssm_delta(16, 32, 128, 1e-6, 8192, nb));
        }
        for s in &srcs {
            assert!(s.starts_with("#version 450") && !s.contains('@'));
        }
    }

    #[test]
    fn shape_and_batch_are_part_of_the_source() {
        assert_ne!(rmsnorm(4096, 1e-6), rmsnorm(256, 1e-6));
        assert_ne!(attn_decode(16, 4, 256, 2048), attn_decode(16, 4, 256, 4096));
        assert_ne!(ssm_delta(16, 32, 128, 1e-6, 8192, 1), ssm_delta(16, 32, 128, 1e-6, 8192, 2));
        assert!(ssm_delta(16, 32, 128, 1e-6, 8192, 2).contains("st1[base + i * 128u + j] = s;"));
    }
}
