"""Generates rust/crates/lev-tokenizer/src/unicode_tables.rs: code point ranges of the Unicode
general categories L (letters), M (marks) and N (numbers), from Python's unicodedata.

    python tools/dev/gen_unicode_tables.py > rust/crates/lev-tokenizer/src/unicode_tables.rs
"""
import sys
import unicodedata


def ranges(prefix):
    out, start, prev = [], None, None
    for cp in range(0x110000):
        if unicodedata.category(chr(cp)).startswith(prefix):
            if start is None:
                start = cp
            prev = cp
        elif start is not None:
            out.append((start, prev))
            start = None
    if start is not None:
        out.append((start, prev))
    return out


print("//! Generated by tools/dev/gen_unicode_tables.py (Unicode %s). Do not edit." % unicodedata.unidata_version)
print()
for name, prefix in (("LETTERS", "L"), ("MARKS", "M"), ("NUMBERS", "N")):
    r = ranges(prefix)
    print("pub const %s: &[(u32, u32)] = &[" % name)
    for i in range(0, len(r), 6):
        print("    " + " ".join("(0x%X, 0x%X)," % t for t in r[i:i + 6]))
    print("];")
    print()